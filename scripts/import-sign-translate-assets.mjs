/**
 * Create a keyframe at `time` seconds with partial joint overrides.
 */
function keyframe(time, overrides = {}) {
  return {
    time,
    pose: {
      joints: { ...REST_POSE, ...overrides },
    },
  };
}

/**
 * Build a complete animation object.
 */
function createAnimation(gesture, duration, keyframes, fps = 30) {
  return {
    version: 1,
    gesture,
    duration,
    fps,
    keyframes,
  };
}

