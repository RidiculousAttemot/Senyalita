/**
 * import-sign-translate-assets.mjs
 *
 * Reference importer for sign/translate repository assets.
 *
 * This script converts open-source pose/animation concepts from the
 * sign/translate repo into SignLangVisual's animation JSON format.
 *
 * The sign/translate repo does NOT contain static JSON keyframe files —
 * all animations are generated dynamically via TFJS models converting
 * MediaPipe Holistic landmarks to Mixamo quaternion keyframes.
 *
 * This converter creates the JSON keyframe structure that SignLangVisual
 * uses for its SVG stickman animation engine.
 *
 * Usage:
 *   node scripts/import-sign-translate-assets.mjs [--input <path>] [--output <path>]
 *
 * License: CC BY-NC-SA 4.0 (sign/translate)
 *   Adapted concepts only — no direct code copying.
 */

