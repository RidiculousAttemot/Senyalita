function ensureDir(dir) {
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
}

function generateJSON() {
  console.log("Importing sign/translate assets into SignLangVisual animation format...");
  console.log();

  ensureDir(OUTPUT_DIR);
  ensureDir(SRC_OUTPUT);

  let count = 0;
  for (const [gesture, def] of Object.entries(GESTURE_DEFINITIONS)) {
    const anim = createAnimation(gesture, def.duration, def.keyframes);
    const filename = gesture.toLowerCase().replace(/\s+/g, "-");

    // Write JSON asset file
    const jsonPath = path.join(OUTPUT_DIR, `${filename}.json`);
    fs.writeFileSync(jsonPath, JSON.stringify(anim, null, 2), "utf-8");
    console.log(`  ✓ ${jsonPath}`);

    // Write JS module
    const jsPath = path.join(SRC_OUTPUT, `${filename}.ts`);
    const jsContent = `import type { GestureAnimation } from "@/features/animation/types";\n\nexport const ${gesture.replace(/\s+/g, "_")}: GestureAnimation = ${JSON.stringify(anim, null, 2)};\n`;
    fs.writeFileSync(jsPath, jsContent, "utf-8");
    console.log(`  ✓ ${jsPath}`);

    count++;
  }

  console.log();
  console.log(`Generated ${count} gesture animations.`);
  console.log(`  JSON output: ${OUTPUT_DIR}`);
  console.log(`  TS output: ${SRC_OUTPUT}`);
  console.log();

  // Generate barrel export
  const barrelContent = Object.keys(GESTURE_DEFINITIONS)
    .map((g) => {
      const name = g.replace(/\s+/g, "_");
      const file = g.toLowerCase().replace(/\s+/g, "-");
      return `export { ${name} } from "./${file}";`;
    })
    .join("\n");

  const barrelPath = path.join(SRC_OUTPUT, "index.ts");
  fs.writeFileSync(barrelPath, barrelContent + "\n", "utf-8");
  console.log(`  ✓ ${barrelPath} (barrel export)`);

  console.log();
  console.log("Done. Assets are ready for SignLangVisual animation engine.");
}

generateJSON();
